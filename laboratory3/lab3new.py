# Условие: Дан одномерный массив целого типа.
# Получить другой массив, состоящий только из нечётных чисел исходного массива,
# или сообщить, что таких чисел нет.
# Полученный массив вывести в порядке убывания элементов.

n = int(input("Введите количество элементов массива: "))

a = []
for i in range(n):
    x = int(input(f"Введите элемент a[{i}]: "))
    a.append(x)

odd = [x for x in a if x % 2 != 0]

if odd:
    odd.sort(reverse=True)
    print("Исходный массив:", a)
    print("Нечётные элементы по убыванию:", odd)
else:
    print("В массиве нет нечётных чисел.")