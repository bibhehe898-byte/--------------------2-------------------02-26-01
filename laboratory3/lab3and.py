# Условие: Дан массив целых чисел.
# Найти максимальный элемент массива и его порядковый номер.

n = int(input("Введите количество элементов массива: "))

a = []
for i in range(n):
    x = int(input(f"Введите элемент a[{i}]: "))
    a.append(x)

max_value = max(a)
max_index = a.index(max_value)  

print("Массив:", a)
print("Максимальный элемент:", max_value)
print("Индекс максимального элемента (с 0):", max_index)
print("Порядковый номер максимального элемента (с 1):", max_index + 1)